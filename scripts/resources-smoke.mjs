import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { expect } from 'playwright/test';
const base = process.env.BASE_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true, reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [], external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (/^https?:/.test(r.url()) && new URL(r.url()).origin !== new URL(base).origin) external.push(r.url()); });
const nav = label => page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: label, exact: true }).click();
try {
  await page.goto(base);
  await expect(page.locator('.quote-card')).toHaveCount(0);
  await nav('资料目录');
  await expect(page.getByText('戒色吧获取：尚未接入')).toBeVisible();
  await expect(page.getByText('这里还没有资料')).toBeVisible();
  await page.screenshot({ path: 'test-results/resources-desktop.png', fullPage: true });
  await page.getByLabel('资料标题').fill('自动化测试来源');
  await page.getByLabel('来源链接').fill('javascript:alert(1)');
  await page.getByRole('button', {name:'保存来源'}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByLabel('来源链接').fill('https://example.com/');
  await page.getByRole('button', {name:'保存来源'}).click();
  await expect(page.locator('.source-item')).toHaveCount(1);
  await expect(page.getByRole('link', {name:'打开外部来源'})).toHaveAttribute('rel', 'noopener noreferrer');
  await page.reload(); await nav('资料目录');
  await expect(page.locator('.source-item')).toHaveCount(1);
  await page.getByRole('button', {name:'阅读笔记', exact:true}).click();
  await expect(page.locator('.source-item')).toHaveCount(0);
  await nav('我的计划'); await page.getByRole('button', {name:'调整目标'}).click();
  await page.getByLabel('我想做出的改变').fill('自动化测试目标');
  await page.getByLabel('目标天数').fill('12');
  await page.getByRole('button', {name:'保存我的目标'}).click();
  await expect(page.getByText('自动化测试目标')).toBeVisible();
  await page.getByRole('button', {name:'偏好设置', exact:true}).click();
  await page.getByRole('switch', {name:'中性鼓励短句'}).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', {name:'导出我的记录'}).click();
  const download = await downloadEvent;
  const stream = await download.createReadStream(); let json = ''; for await (const chunk of stream) json += chunk;
  const backup = JSON.parse(json);
  assert.equal(backup.resources.length, 1); assert.equal(backup.goalDays, 12); assert.equal(backup.preferences.encouragement, true);
  await page.reload(); await expect(page.locator('.quote-card')).toHaveCount(1);
  await nav('静心工具'); await page.getByRole('button', {name:/02 \/ FOCUS/}).click();
  await page.getByRole('button', {name:'开始专注', exact:true}).click();
  await page.waitForTimeout(1100); await page.getByRole('button', {name:'暂停', exact:true}).click();
  const paused = await page.locator('.focus-clock > span').textContent();
  await page.waitForTimeout(1100); await expect(page.locator('.focus-clock > span')).toHaveText(paused);
  await page.getByRole('button', {name:'关闭弹窗'}).click();
  await nav('资料目录');
  await page.getByRole('button', {name:'删除来源 自动化测试来源'}).click();
  await page.getByRole('button', {name:'确认删除来源'}).click();
  await expect(page.locator('.source-item')).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator(".sidebar")).toHaveAttribute("inert", "");
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:'test-results/resources-mobile.png',fullPage:true});
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('PASS: source empty state, URL safety, save/reload/filter/delete, custom goals, encouragement persistence, JSON export, timer pause, mobile layout, zero external requests.');
} finally { await browser.close(); }
